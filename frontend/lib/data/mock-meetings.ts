export function getWorkspaceStats(meetings: Meeting[]): WorkspaceStats {
  let confirmed = 0;
  let clarifications = 0;
  let ideas = 0;
  let synced = 0;

  meetings.forEach((m) => {
    confirmed += m.confirmed_tasks.length;
    clarifications += m.clarifications_needed.filter((c) => c.status !== 'resolved').length;
    ideas += m.speculative_ideas.length;
    synced += m.confirmed_tasks.filter((t) => t.trello_status === 'synced').length;
  });

  return {
    confirmed_actions_count: confirmed,
    clarifications_pending_count: clarifications,
    ideas_captured_count: ideas,
    synced_tasks_count: synced,
    total_meetings_count: meetings.length,
  };
}
